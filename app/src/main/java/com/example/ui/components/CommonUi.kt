/**
 * تنسيق المبالغ المالية بالدينار العراقي بأرقام صحيحة واضحة.
 */
fun formatIqd(amount: Long): String {
    val formatter = NumberFormat.getInstance(Locale("ar", "IQ"))
    return "${formatter.format(amount)} د.ع"
}

